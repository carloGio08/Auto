import type { Plugin } from 'vite';

/**
 * Emits `sw.js` at build time with the list of every generated asset, so the game can be
 * precached and played offline after the first visit. Cache name changes with each build.
 */
export function serviceWorkerPlugin(): Plugin {
  return {
    name: 'mountain-drop-sw',
    apply: 'build',
    generateBundle(_options, bundle) {
      const files = Object.keys(bundle).filter((f) => !f.endsWith('.map') && f !== 'sw.js');
      const assets = [
        './',
        ...files.map((f) => `./${f}`),
        './manifest.webmanifest',
        './icon.svg',
        './icon-maskable.svg',
      ];
      const version = `md-${Date.now().toString(36)}`;
      const source = `/* Generated by vite-plugins/serviceWorker.ts */
const CACHE = ${JSON.stringify(version)};
const ASSETS = ${JSON.stringify([...new Set(assets)])};

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(ASSETS)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return;
  if (req.mode === 'navigate') {
    // Network first for the page so updates arrive, cache as offline fallback.
    event.respondWith(
      fetch(req)
        .then((res) => {
          const copy = res.clone();
          caches.open(CACHE).then((c) => c.put('./', copy));
          return res;
        })
        .catch(() => caches.match('./')),
    );
    return;
  }
  event.respondWith(
    caches.match(req).then((hit) => hit || fetch(req).then((res) => {
      if (res.ok) {
        const copy = res.clone();
        caches.open(CACHE).then((c) => c.put(req, copy));
      }
      return res;
    })),
  );
});
`;
      this.emitFile({ type: 'asset', fileName: 'sw.js', source });
    },
  };
}
